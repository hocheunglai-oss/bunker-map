    await t.test("shared backup writer locks coexist; the exclusive fence genuinely blocks a writer in another backend", async () => {
      const a = await f.session("advisory-a"), b = await f.session("advisory-b"), observer = await f.session("advisory-observer")
      const before = await f.state()
      await a.begin("SYNTHETIC-ADVISORY-A")
      await a.query("update public.remarks set content='Uncommitted first' where id=1;")
      await b.begin("SYNTHETIC-ADVISORY-B")
      await b.query("update public.remarks set content='Committed second' where id=2;")
      const shared = await f.owner.one(`select jsonb_agg(jsonb_build_object('pid',pid,'mode',mode,'granted',granted) order by pid) from pg_locks where locktype='advisory' and pid in (${a.pid},${b.pid});`)
      assert.equal(shared.length, 2)
      assert.ok(shared.every(lock => lock.mode === "ShareLock" && lock.granted))
      assert.equal((await fence(observer)).ready, false)
      await b.query("commit;")
      assert.equal((await fence(observer)).ready, false, "another writer remains active")
      await a.query("rollback;")
      const committed = await f.state()
      assert.equal(committed.epochs.length - before.epochs.length, 1)
      assert.equal(committed.audit.length - before.audit.length, 1)
      assert.equal(committed.remarks.find(remark => remark.id === 1).content, before.remarks.find(remark => remark.id === 1).content)
      assert.equal(committed.remarks.find(remark => remark.id === 2).content, "Committed second")
      await observer.begin("SYNTHETIC-FENCE-HOLDER")
      assert.equal((await fence(observer)).ready, true)
      await a.begin("SYNTHETIC-BLOCKED-WRITER")
      const pending = settle(a.query("update public.remarks set content='After exclusive fence' where id=1;"))
      const blocked = await waitForBlock(f.owner, a, observer, "advisory")
      t.diagnostic(`Real backup-advisory blocking: fence holder ${observer.pid}; ${JSON.stringify(blocked)}`)
      assert.ok(blocked.waiting.some(lock => lock.type === "advisory" && lock.mode === "ShareLock"))
      assert.deepEqual(await f.state(), committed)
      await observer.query("commit;")
      assert.equal((await pending).error, undefined)
      await a.query("commit;")
      const after = await f.state()
      assert.equal(after.epochs.length - committed.epochs.length, 1)
      assert.equal(after.audit.length - committed.audit.length, 1)
      assert.ok((await fence(b)).epoch > committed.epochs.at(-1).mutation_id)
      await Promise.all([a.close(), b.close(), observer.close()])
    })

