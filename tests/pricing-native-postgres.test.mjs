    await t.test("a blocked stale save rechecks after commit; audit and epoch commit once; replay writes nothing", async () => {
      const a = await f.session("save-a"), b = await f.session("save-b"), observer = await f.session("save-observer")
      const expected = await row(f), before = await f.state()
      const correlation = await a.begin("SYNTHETIC-SAVE-A")
      const first = await a.one(saveSql(expected, 777))
      assert.equal(first.replayed, false)
      await b.begin("SYNTHETIC-SAVE-B")
      const pending = settle(b.one(saveSql(expected, 888)))
      const blocked = await waitForBlock(observer, b, a, "relation")
      t.diagnostic(`Real stale-save blocking: holder ${a.pid}; ${JSON.stringify(blocked)}`)
      assert.ok(blocked.waiting.some(lock => lock.relation === "ports" && lock.mode === "ShareRowExclusiveLock"))
      assert.deepEqual(await f.state(), before, "uncommitted prices, audit and mutation markers stay invisible to another backend")
      assert.deepEqual(await fence(observer), { schema: "bunker-map.backup-export-fence/v1", ready: false, epoch: null })
      await a.query("commit;")
      const second = await pending
      assert.equal(second.error?.code, "P0002")
      assert.match(second.error?.message, /Saved port changed/)
      const saved = await f.state()
      assert.equal(saved.ports.find(port => port.id === basis).hsfo, 777)
      assert.equal(saved.ports.find(port => port.id === linked).updated_at, "2026-10-09")
      assert.equal(saved.history.length - before.history.length, 1)
      const audit = saved.audit.filter(log => log.request_context.correlationId === correlation)
      assert.equal(audit.length, 2, "one changed-price row and one history insertion, not linked-date-only noise")
      assert.ok(audit.every(log => log.actor_id === "SYNTHETIC-SAVE-A" && log.actor_source === "header" && log.request_context.pageId === "pricesetter"))
      const portAudit = audit.find(log => log.table_name === "ports")
      assert.equal(portAudit.before_row.hsfo, expected.hsfo)
      assert.equal(portAudit.after_row.hsfo, 777)
      assert.equal(saved.epochs.length - before.epochs.length, 1, "all price/history/audit statements share one committed transaction marker")
      const confirmedFence = await fence(observer)
      assert.equal(confirmedFence.ready, true)
      assert.equal(confirmedFence.epoch, saved.epochs.at(-1).mutation_id)
      await a.begin("SYNTHETIC-EXACT-REPLAY")
      assert.equal((await a.one(saveSql(expected, 777))).replayed, true)
      await a.query("commit;")
      assert.deepEqual(await f.state(), saved, "confirmed replay must not add history, audit or epoch evidence")
      await Promise.all([a.close(), b.close(), observer.close()])
    })

