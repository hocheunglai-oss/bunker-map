/* Run with node tests/phonebook-sync.browser.test.cjs.
 * Playwright can be provided by NODE_PATH and a separately launched headless
 * Chrome by CHROME_EXECUTABLE_PATH. --serve exposes synthetic data for a visual
 * agent-browser check. All browser data and writes remain in memory.
 */
const assert = require("node:assert/strict")
const http = require("node:http")
const path = require("node:path")
const { build } = require("esbuild")
const { readFileSync } = require("node:fs")

const root = path.resolve(__dirname, "..")
const RETRY_KEY = "phonebook_carddav_pending:v2"
const button = (page, name) => page.getByRole("button", { name, exact: true })
const company = (page, name = "ALPHA SHIPPING") => page.getByRole("button", { name: new RegExp(`^${name}`) })
const contact = (page, name = "ALICE TEST") => page.getByRole("button", { name: new RegExp(`^${name}`) })
const field = (page, name) => page.getByText(name, { exact: true }).locator("..").locator("input")
const requests = (page) => page.evaluate(() => window.__phonebookSyncHarness.requests.filter((request) => request.url === "/api/phonebook/carddav-sync" && request.method === "POST"))
const retries = (page) => page.evaluate((key) => JSON.parse(localStorage.getItem(key) || "[]"), RETRY_KEY)
const settle = (page) => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))

async function main() {
  const mocks = path.join(root, "tests/fixtures/phonebook-sync-mocks.ts")
  const bundle = await build({
    absWorkingDir: root, entryPoints: ["tests/fixtures/phonebook-sync-page.tsx"], bundle: true,
    write: false, outdir: "phonebook-browser-fixture", platform: "browser", format: "iife", jsx: "automatic", logLevel: "warning",
    define: { "process.env.NODE_ENV": '"development"' },
    plugins: [{ name: "synthetic-phonebook-boundaries", setup(builder) {
      builder.onResolve({ filter: /^@\/lib\/(supabase|useSimpleAdminAuth)$/ }, () => ({ path: mocks }))
    } }],
  })
  const assets = new Map(bundle.outputFiles.map((file) => [`/${path.basename(file.path)}`, file.contents]))
  const script = [...assets.keys()].find((name) => name.endsWith(".js"))
  const adminTheme = readFileSync(path.join(root, "app/globals.css"), "utf8").match(/\.fc-admin-scope\s*\{[\s\S]*?\}/)?.[0]
  assert.ok(adminTheme, "Use the real admin theme variables for visual verification")
  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Local Phonebook sync regression</title><style>
  :root { --fc-admin-page-bg:#f4f5f8; --fc-admin-font:Arial,sans-serif; --fc-admin-panel-text:#20232a; --fc-admin-heading:#20232a; --fc-admin-panel-bg:#fff; --fc-admin-panel-soft-bg:#f8f9fc; --fc-admin-border:#ccd0d8; --fc-admin-border-soft:#dfe2e8; --fc-admin-muted:#69707d; --fc-admin-button-bg:#f4f5f8; --fc-admin-button-text:#20232a; --fc-admin-button-border:#ccd0d8; --fc-admin-primary-button-bg:#0672ed; --fc-admin-primary-button-text:#fff; --fc-admin-selected-bg:#e7f2ff; --fc-admin-selected-border:#0672ed; --fc-admin-success-bg:#218838; --fc-admin-success-text:#218838; --fc-admin-success-border:#218838; --fc-admin-danger-bg:#dc001b; --fc-admin-danger-text:#dc001b; --fc-admin-danger-border:#dc001b; --fc-admin-warning-bg:#fff3bf; --fc-admin-warning-text:#704b00; --fc-admin-warning-border:#e9be38; --fc-admin-link:#0672ed; --fc-input-border:#ccd0d8; --fc-tool-input-bg:#fff; --fc-tool-input-text:#20232a; }
  * { box-sizing:border-box; } body { margin:0; font-family:Arial,sans-serif; } button,input,select { font:inherit; } button:disabled { opacity:.55; cursor:default!important; }
  ${adminTheme}
  </style></head><body><div id="root" class="fc-admin-scope"></div><script src="${script}"></script></body></html>`
  const server = http.createServer((request, response) => {
    if (request.method !== "GET") { response.writeHead(405); response.end("Read-only fixture server"); return }
    const asset = assets.get(new URL(request.url, "http://127.0.0.1").pathname)
    response.setHeader("Content-Type", asset ? "text/javascript" : "text/html")
    response.end(asset || html)
  })
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve))
  const baseUrl = `http://127.0.0.1:${server.address().port}`
  let browser
  try {
    if (process.argv.includes("--serve")) {
      console.log(`Synthetic Phonebook sync fixture: ${baseUrl}`)
      await new Promise((resolve) => {
        const stop = () => { process.removeListener("SIGINT", stop); process.removeListener("SIGTERM", stop); resolve() }
        process.once("SIGINT", stop); process.once("SIGTERM", stop)
      })
      return
    }
    const engine = process.env.BROWSER_ENGINE || "chromium"
    const browserType = require("playwright")[engine]
    browser = await browserType.launch({ headless: true, ...(engine === "chromium" && process.env.CHROME_EXECUTABLE_PATH ? { executablePath: process.env.CHROME_EXECUTABLE_PATH } : {}) })
    const errors = []
    const blockedRequests = []
    let context
    let page
    async function reset() {
      if (context) await context.close()
      context = await browser.newContext({ viewport: { width: Number(process.env.PHONEBOOK_TEST_WIDTH || 1440), height: 1000 }, colorScheme: process.env.PHONEBOOK_TEST_SCHEME || "light" })
      await context.route("**/*", (route) => {
        if (new URL(route.request().url()).origin === baseUrl) return route.continue()
        blockedRequests.push(route.request().url())
        return route.abort()
      })
      page = await context.newPage()
      page.setDefaultTimeout(8000)
      page.on("pageerror", (error) => errors.push(error.message))
      page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()) })
      await page.goto(baseUrl)
      await company(page).waitFor()
    }
    async function selectCompany(name = "ALPHA SHIPPING", firstContact = "ALICE TEST") {
      await company(page, name).click()
      await contact(page, firstContact).waitFor()
    }
    async function syncCompany() {
      await button(page, "Sync selected company").click()
      await page.waitForFunction(() => window.__phonebookSyncHarness.activeSyncs === 0)
      await button(page, "Sync selected company").waitFor()
      await settle(page)
    }
    async function retry() {
      await button(page, "☰").click()
      await button(page, "Retry Failed").click()
      await button(page, "Sync selected company").waitFor()
      await settle(page)
    }

    await reset()
    await company(page).dblclick()
    let saveDialog = page.getByRole("dialog", { name: "Company details" })
    await saveDialog.getByRole("button", { name: "Save", exact: true }).waitFor()
    await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").fill("RENAMED SHIPPING")
    await saveDialog.getByRole("button", { name: "Save", exact: true }).click()
    await company(page, "RENAMED SHIPPING").waitFor()
    await page.waitForFunction(() => window.__phonebookSyncHarness.activeSyncs === 0)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.requests.filter((r) => r.url === "/api/phonebook/company" && r.method === "POST").length), 1)
    assert.deepEqual(await page.evaluate(() => window.__phonebookSyncHarness.operations.filter((op) => op.method === "PATCH")), [], "company rename must not issue a browser-dependent company/contact write cascade")
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.filter((row) => row.company === "RENAMED SHIPPING").length), 3)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.companies[0].tel_no_1), "22334455")
    await reset()
    await company(page).dblclick()
    saveDialog = page.getByRole("dialog", { name: "Company details" })
    await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").fill("UNSAVED COMPANY DRAFT")
    await page.evaluate(() => { window.__phonebookSyncHarness.companySaveStatus = 409 })
    await saveDialog.getByRole("button", { name: "Save", exact: true }).click()
    await page.getByText("This company changed or was removed. Your edits are still here; reopen it before saving again.", { exact: true }).waitFor()
    assert.equal(await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").inputValue(), "UNSAVED COMPANY DRAFT")
    assert.equal(await saveDialog.getByRole("button", { name: "Save", exact: true }).isEnabled(), true)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.companies[0].name), "ALPHA SHIPPING")
    if (process.env.PHONEBOOK_SCREENSHOT) await page.screenshot({ path: process.env.PHONEBOOK_SCREENSHOT, fullPage: true })
    assert.deepEqual(errors, [], "no browser errors in atomic company save")
    await reset()
    await company(page).dblclick()
    saveDialog = page.getByRole("dialog", { name: "Company details" })
    await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").fill("HELD COMPANY SAVE")
    await page.evaluate(() => { window.__phonebookSyncHarness.deferCompanySave = true })
    await saveDialog.getByRole("button", { name: "Save", exact: true }).click()
    await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseCompanySave))
    assert.equal(await saveDialog.getByRole("button", { name: "Close", exact: true }).isDisabled(), true)
    assert.equal(await saveDialog.getByRole("button", { name: "Delete", exact: true }).isDisabled(), true)
    assert.equal(await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").isDisabled(), true)
    await saveDialog.getByRole("button", { name: "Close", exact: true }).evaluate((node) => node.click())
    assert.equal(await saveDialog.isVisible(), true, "a pending company save cannot close and replace the active draft")
    await page.evaluate(() => window.__phonebookSyncHarness.releaseCompanySave())
    await company(page, "HELD COMPANY SAVE").waitFor()
    await reset()
    await page.evaluate(() => { window.__phonebookSyncHarness.companyReadPlan = [true, true] })
    await company(page).dblclick()
    saveDialog = page.getByRole("dialog", { name: "Company details" })
    await page.waitForFunction(() => window.__phonebookSyncHarness.releaseCompanyReads?.length === 1)
    await saveDialog.getByRole("button", { name: "Close", exact: true }).click()
    await company(page).dblclick()
    await page.waitForFunction(() => window.__phonebookSyncHarness.releaseCompanyReads?.length === 2)
    await page.evaluate(() => window.__phonebookSyncHarness.releaseCompanyReads[1]())
    await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").fill("NEWER LOCAL COMPANY DRAFT")
    await page.evaluate(() => window.__phonebookSyncHarness.releaseCompanyReads[0]())
    await settle(page)
    assert.equal(await saveDialog.getByText("Company Name", { exact: true }).locator("..").locator("input").inputValue(), "NEWER LOCAL COMPANY DRAFT", "an older load for the same company cannot replace a reopened newer draft")
    console.log(`PASS: atomic company save and stale draft retention (${engine}, ${process.env.PHONEBOOK_TEST_WIDTH || 1440}px, ${process.env.PHONEBOOK_TEST_SCHEME || "light"})`)
    if (process.argv.includes("--company-only")) return

    await reset()
    assert.equal(await button(page, "Sync selected company").count(), 1)
    assert.equal(await page.getByRole("button", { name: /^Synced \d+ Contacts$/ }).count(), 0)
    await page.getByText("FC Uno: 4 · CardDAV total: 9 (4 FC Uno + 5 other)", { exact: true }).waitFor()
    await button(page, "Refresh phonebook counts").click()
    await page.getByText("FC Uno: 4 · CardDAV total: 9 (4 FC Uno + 5 other)", { exact: true }).waitFor()
    await page.getByText("Matched by ID: 4 · Missing: 0 · Extra FC Uno IDs: 0", { exact: true }).waitFor()
    assert.deepEqual(await requests(page), [], "a directory count is not evidence of remote sync")
    await page.evaluate(() => { window.__phonebookSyncHarness.countOverrides = { carddavMatchedCount: 3, carddavMissingCount: 1, carddavOrphanCount: 1 } })
    await button(page, "Refresh phonebook counts").click()
    await page.getByText("Matched by ID: 3 · Missing: 1 · Extra FC Uno IDs: 1", { exact: true }).waitFor()
    assert.deepEqual(await requests(page), [], "count mismatches never trigger automatic repairs or deletions")
    assert.deepEqual(await page.evaluate(() => window.__phonebookSyncHarness.operations), [])
    await selectCompany()
    // Add a contact after the UI cached the company: sync must re-fetch its IDs.
    await page.evaluate(() => {
      window.__phonebookSyncHarness.contacts.push({ id: "synthetic-contact-new", full_name: "NEW SERVER CONTACT", company: "ALPHA SHIPPING", favorite: false })
      window.__phonebookSyncHarness.requests.length = 0
    })
    assert.equal(await contact(page, "NEW SERVER CONTACT").count(), 0)
    await syncCompany()
    const companyRequests = await requests(page)
    assert.equal(companyRequests.length, 2)
    assert.ok(companyRequests.every((request) => request.body.contactIds.length <= 2))
    assert.deepEqual(companyRequests.flatMap((request) => request.body.contactIds).sort(), ["synthetic-contact-a", "synthetic-contact-b", "synthetic-contact-c", "synthetic-contact-new"])
    const refreshed = await page.evaluate(() => window.__phonebookSyncHarness.requests.findIndex((request) => request.url.includes("company=ALPHA%20SHIPPING")))
    assert.ok(refreshed >= 0, "sync fetches the authoritative company list")
    assert.deepEqual(await retries(page), [])
    console.log("PASS: truthful idle label; company sync re-fetches IDs and sends batches of at most two")

    await reset()
    await selectCompany()
    await page.evaluate(() => { window.__phonebookSyncHarness.syncPlan.push({ failedIds: ["synthetic-contact-a"] }) })
    await syncCompany()
    assert.deepEqual((await retries(page)).map((entry) => [entry.id, entry.operation]), [["synthetic-contact-a", "upsert"]])
    await page.getByText(/Synthetic verification failure/).waitFor()
    await selectCompany("BETA SHIPPING", "DAVE TEST")
    await syncCompany()
    assert.deepEqual((await retries(page)).map((entry) => entry.id), ["synthetic-contact-a"], "unrelated success preserves a failed contact")
    const beforeRetry = (await requests(page)).length
    await retry()
    assert.deepEqual((await requests(page)).slice(beforeRetry).map((request) => request.body), [{ contactIds: ["synthetic-contact-a"] }])
    assert.deepEqual(await retries(page), [])
    console.log("PASS: partial 207 keeps failed contacts queued across unrelated success; Retry targets them")

    await reset()
    await selectCompany()
    await contact(page).click()
    await button(page, "Edit").click()
    await field(page, "Mobile 1").fill("+85295556666")
    await page.evaluate(() => { window.__phonebookSyncHarness.syncPlan.push({ reject: true }) })
    await button(page, "Save").click()
    await page.getByText(/Synthetic CardDAV network failure/).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts[0].mobile_1), "+85295556666", "local Save must survive a remote failure")
    assert.deepEqual((await retries(page)).map((entry) => entry.id), ["synthetic-contact-a"])
    await retry()
    assert.deepEqual(await retries(page), [])
    console.log("PASS: saved edits survive network failure and can be retried without delete/recreate")

    await reset()
    await selectCompany()
    await contact(page).click()
    await button(page, "Edit").click()
    await field(page, "Mobile 1").fill("+85295556666")
    // Another user deletes the row after this editor loaded it. PostgREST
    // legitimately returns a successful PATCH with zero affected rows.
    await page.evaluate(() => {
      const rows = window.__phonebookSyncHarness.contacts
      rows.splice(rows.findIndex((row) => row.id === "synthetic-contact-a"), 1)
    })
    await button(page, "Save").click()
    await page.getByText("This contact changed or no longer exists. Your changes have not been saved; refresh the directory before trying again.", { exact: true }).waitFor()
    assert.equal(await field(page, "Mobile 1").inputValue(), "+85295556666", "unsaved edits remain available")
    assert.deepEqual(await requests(page), [], "a zero-row save must not claim a saved contact or start a remote upsert")
    assert.deepEqual(await retries(page), [], "an uncommitted edit must not create a browser retry operation")
    assert.equal(await button(page, "Save").isEnabled(), true)
    console.log("PASS: an externally deleted contact cannot be falsely acknowledged as saved or synced")

    await reset()
    await selectCompany()
    await contact(page).click()
    await button(page, "Edit").click()
    await field(page, "Mobile 1").fill("+85295556666")
    await page.evaluate(() => {
      window.__phonebookSyncHarness.contacts[0].favorite = true
      window.__phonebookSyncHarness.contactWriteFailure = "reject"
    })
    await button(page, "Save").click()
    await page.getByText("Contact save was not confirmed. Your changes are still here; check the directory before trying Save again.", { exact: true }).waitFor()
    assert.equal(await field(page, "Mobile 1").inputValue(), "+85295556666")
    assert.equal(await button(page, "Save").isEnabled(), true)
    assert.deepEqual(await requests(page), [])
    await button(page, "Save").click()
    await page.getByText("Saved and verified on CardDAV.", { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts[0].favorite), true, "editing phone details must not erase an unrelated saved favourite")
    console.log("PASS: a thrown save preserves the draft and restores Save; retry leaves unrelated favourite intact")

    await reset()
    await selectCompany()
    await button(page, "New Contact").click()
    const createDialog = page.getByRole("dialog", { name: "New contact", exact: true })
    await createDialog.waitFor()
    await createDialog.getByText("Name", { exact: true }).locator("..").locator("input").fill("LOST REPLY CONTACT")
    await page.evaluate(() => { window.__phonebookSyncHarness.contactWriteFailure = "commit-reject" })
    await createDialog.getByRole("button", { name: "Save", exact: true }).click()
    await page.getByText("Contact save was not confirmed. Your changes are still here; check the directory before trying Save again.", { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.filter((row) => row.full_name === "LOST REPLY CONTACT").length), 1)
    await createDialog.getByRole("button", { name: "Save", exact: true }).click()
    await page.getByText("Saved and verified on CardDAV.", { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.filter((row) => row.full_name === "LOST REPLY CONTACT").length), 1, "retrying a committed insert after a lost reply must not create a second contact")
    const createOperations = await page.evaluate(() => window.__phonebookSyncHarness.operations.filter((operation) => operation.table === "phonebook_contacts" && operation.method === "POST"))
    assert.equal(createOperations.length, 2)
    assert.ok(createOperations[0].payload.id)
    assert.equal(createOperations[0].payload.id, createOperations[1].payload.id)
    assert.equal(createOperations[0].payload.source_key, createOperations[1].payload.source_key)
    console.log("PASS: retrying a committed new-contact insert uses one stable identity and cannot duplicate it")

    for (const [changedField, changedValue] of [["mobile_1", "+85298889999"], ["favorite", true]]) {
      await reset()
      await selectCompany()
      await button(page, "New Contact").click()
      const conflictingCreate = page.getByRole("dialog", { name: "New contact", exact: true })
      await conflictingCreate.getByText("Name", { exact: true }).locator("..").locator("input").fill("CONCURRENT CREATE CONTACT")
      await page.evaluate(() => { window.__phonebookSyncHarness.contactWriteFailure = "commit-reject" })
      await conflictingCreate.getByRole("button", { name: "Save", exact: true }).click()
      await conflictingCreate.getByRole("alert").filter({ hasText: "Contact save was not confirmed" }).waitFor()
      await page.evaluate(([fieldName, value]) => { window.__phonebookSyncHarness.contacts.find((row) => row.full_name === "CONCURRENT CREATE CONTACT")[fieldName] = value }, [changedField, changedValue])
      await conflictingCreate.getByRole("button", { name: "Save", exact: true }).click()
      await conflictingCreate.getByRole("alert").filter({ hasText: "A contact from this Save may already exist with different details" }).waitFor()
      assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.filter((row) => row.full_name === "CONCURRENT CREATE CONTACT").length), 1)
      assert.equal(await page.evaluate((fieldName) => window.__phonebookSyncHarness.contacts.find((row) => row.full_name === "CONCURRENT CREATE CONTACT")[fieldName], changedField), changedValue, "replay must not overwrite another user's later edit")
      assert.deepEqual(await requests(page), [], "unconfirmed changed data must not be sent as a verified creation")
      assert.equal(await conflictingCreate.getByRole("button", { name: "Save", exact: true }).isEnabled(), true)
    }
    console.log("PASS: new-contact replay refuses changed details or favourite without overwriting or duplicating")

    await reset()
    await selectCompany()
    await contact(page).click()
    await button(page, "Edit").click()
    await field(page, "Mobile 1").fill("+85295556666")
    await page.evaluate(() => { window.__phonebookSyncHarness.deferContactWrite = true })
    await button(page, "Save").click()
    await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseContactWrite))
    assert.equal(await field(page, "Mobile 1").isDisabled(), true)
    assert.equal(await button(page, "Cancel").isDisabled(), true)
    assert.equal(await button(page, "Delete").isDisabled(), true)
    assert.equal(await company(page, "BETA SHIPPING").isDisabled(), true)
    assert.equal(await button(page, "New Contact").isDisabled(), true)
    assert.equal(await button(page, "New Company").isDisabled(), true)
    assert.equal(await button(page, "All Companies").isDisabled(), true)
    await page.evaluate(() => window.__phonebookSyncHarness.releaseContactWrite())
    await page.getByText("Saved and verified on CardDAV.", { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts[0].mobile_1), "+85295556666")
    assert.equal(await company(page, "BETA SHIPPING").isEnabled(), true)
    console.log("PASS: pending persistence locks typing, Cancel, Delete and navigation without discarding newer input")

    await reset()
    await selectCompany()
    await button(page, "New Contact").click()
    const pendingCreate = page.getByRole("dialog", { name: "New contact", exact: true })
    const pendingName = pendingCreate.getByText("Name", { exact: true }).locator("..").locator("input")
    await pendingName.fill("PENDING CREATE CONTACT")
    await page.evaluate(() => { window.__phonebookSyncHarness.deferContactWrite = true })
    await pendingCreate.getByRole("button", { name: "Save", exact: true }).click()
    await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseContactWrite))
    assert.equal(await pendingName.isDisabled(), true)
    assert.equal(await pendingCreate.getByRole("button", { name: "Close", exact: true }).isDisabled(), true)
    await page.evaluate(() => window.__phonebookSyncHarness.releaseContactWrite())
    await page.getByText("Saved and verified on CardDAV.", { exact: true }).waitFor()
    assert.equal(await pendingCreate.count(), 0)
    console.log("PASS: a pending new contact cannot be edited or closed before its acknowledgement")

    for (const reject of [false, true]) {
      await reset()
      await selectCompany()
      await contact(page).click()
      await button(page, "Edit").click()
      await field(page, "Mobile 1").fill("+85295556666")
      await page.evaluate((fail) => { window.__phonebookSyncHarness.syncPlan.push({ defer: true, reject: fail }) }, reject)
      await button(page, "Save").click()
      await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseSync))
      const oldPending = await retries(page)
      // Remote verification may be slow, but an acknowledged database save must
      // not keep the page locked. Its late completion must not unlock save #2.
      await contact(page, "BOB TEST").click()
      await button(page, "Edit").click()
      await field(page, "Mobile 1").fill("+85296667777")
      await page.evaluate(() => { window.__phonebookSyncHarness.deferContactWrite = true })
      await button(page, "Save").click()
      await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseContactWrite))
      await page.evaluate(() => window.__phonebookSyncHarness.releaseSync())
      await page.waitForFunction(() => window.__phonebookSyncHarness.activeSyncs === 0)
      await settle(page)
      assert.equal(await field(page, "Mobile 1").isDisabled(), true, "the first sync's finally block cannot release the second database save")
      assert.equal(await button(page, "Cancel").isDisabled(), true)
      assert.equal(await page.getByText("Saved and verified on CardDAV.", { exact: true }).count(), 0, "an older contact's sync must not acknowledge the newer pending save")
      assert.equal(await page.getByText(/Synthetic CardDAV network failure/).count(), 0, "an older failure must not replace the newer pending save's feedback")
      assert.deepEqual(await retries(page), reject ? oldPending : [], "the earlier failed operation and token remain exactly intact")
      await page.evaluate(() => window.__phonebookSyncHarness.releaseContactWrite())
      await page.waitForFunction(() => window.__phonebookSyncHarness.contacts.find((row) => row.full_name === "BOB TEST").mobile_1 === "+85296667777")
      await page.getByText(/^Saved and verified on CardDAV\./).waitFor()
      assert.deepEqual(await retries(page), reject ? oldPending : [], "the newer successful save cannot acknowledge the earlier failed contact")
    }
    console.log("PASS: old sync success/failure cannot unlock or acknowledge a newer pending save; failed tokens survive")

    for (const reject of [false, true]) {
      await reset()
      await selectCompany()
      await contact(page).click()
      await button(page, "Edit").click()
      await field(page, "Mobile 1").fill("+85295556666")
      await page.evaluate((fail) => { window.__phonebookSyncHarness.syncPlan.push({ defer: true, reject: fail }) }, reject)
      await button(page, "Save").click()
      await page.waitForFunction(() => Boolean(window.__phonebookSyncHarness.releaseSync))
      await contact(page, "BOB TEST").click()
      await button(page, "Edit").click()
      await field(page, "Mobile 1").fill("+85296667777")
      await page.evaluate(() => window.__phonebookSyncHarness.releaseSync())
      await page.waitForFunction(() => window.__phonebookSyncHarness.activeSyncs === 0)
      await settle(page)
      assert.equal(await field(page, "Mobile 1").inputValue(), "+85296667777")
      assert.equal(await page.getByText("Saved and verified on CardDAV.", { exact: true }).count(), 0)
      assert.equal(await page.getByText(/Synthetic CardDAV network failure/).count(), 0, "an older job must not replace feedback for the newer draft")
      assert.deepEqual((await retries(page)).map((entry) => entry.id), reject ? ["synthetic-contact-a"] : [], "suppressing stale feedback must never suppress the durable failed operation")
    }
    console.log("PASS: older sync feedback cannot replace a newer draft; real failures remain in Retry Failed")

    await reset()
    await selectCompany()
    await contact(page).click()
    await button(page, "Edit").click()
    await page.evaluate(() => { window.__phonebookSyncHarness.syncPlan.push({ status: 503 }) })
    page.once("dialog", (dialog) => dialog.accept())
    await button(page, "Delete").click()
    await page.getByText(/Synthetic upstream sync failure/).waitFor()
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.some((row) => row.id === "synthetic-contact-a")), false)
    assert.deepEqual((await retries(page)).map((entry) => [entry.id, entry.operation]), [["synthetic-contact-a", "delete"]])
    const beforeDeleteRetry = (await requests(page)).length
    await retry()
    assert.deepEqual((await requests(page)).slice(beforeDeleteRetry).map((request) => request.body), [{ deleteContactIds: ["synthetic-contact-a"] }])
    assert.deepEqual(await retries(page), [])
    console.log("PASS: a failed deletion is retried as DELETE, never as an upsert of a removed record")

    await reset()
    await selectCompany("BETA SHIPPING", "DAVE TEST")
    await contact(page, "DAVE TEST").click()
    await button(page, "Edit").click()
    await page.evaluate(() => { window.__phonebookSyncHarness.failCompanyDeletes = true })
    const acceptDeletion = (dialog) => dialog.accept()
    page.on("dialog", acceptDeletion)
    await button(page, "Delete").click()
    await page.getByText("Contact deleted and CardDAV deletion verified, but company could not be deleted.", { exact: true }).waitFor()
    page.off("dialog", acceptDeletion)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.some((row) => row.id === "synthetic-contact-d")), false)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.companies.some((row) => row.id === "synthetic-company-b")), true)
    assert.deepEqual(await page.evaluate(() => window.__phonebookSyncHarness.companyDeleteRetrySnapshots.map((entries) => entries.map(({ id, operation }) => [id, operation]))), [[["synthetic-contact-d", "delete"]]], "contact deletion must be staged before optional company deletion")
    assert.deepEqual((await requests(page)).map((request) => request.body), [{ deleteContactIds: ["synthetic-contact-d"] }])
    assert.deepEqual(await retries(page), [])
    console.log("PASS: deleting the final contact still syncs its deletion when optional company deletion fails")

    await reset()
    await company(page).dblclick()
    const companyDialog = page.getByRole("dialog", { name: "Company details" })
    await companyDialog.waitFor()
    await page.evaluate(() => {
      window.__phonebookSyncHarness.failCompanyDeletes = true
      window.__phonebookSyncHarness.syncPlan.push({ status: 503 })
    })
    page.on("dialog", acceptDeletion)
    await companyDialog.getByRole("button", { name: "Delete", exact: true }).click()
    await page.getByText(/Contacts deleted, but company could not be deleted and CardDAV deletions remain unverified/).waitFor()
    page.off("dialog", acceptDeletion)
    const deletedIds = ["synthetic-contact-a", "synthetic-contact-b", "synthetic-contact-c"]
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.contacts.some((row) => row.company === "ALPHA SHIPPING")), false)
    assert.equal(await page.evaluate(() => window.__phonebookSyncHarness.companies.some((row) => row.id === "synthetic-company-a")), true)
    assert.deepEqual(await page.evaluate(() => window.__phonebookSyncHarness.companyDeleteRetrySnapshots.map((entries) => entries.map(({ id, operation }) => [id, operation]))), [deletedIds.map((id) => [id, "delete"])], "every confirmed contact deletion must be staged before company deletion")
    assert.deepEqual((await retries(page)).map((entry) => [entry.id, entry.operation]), deletedIds.map((id) => [id, "delete"]))
    await companyDialog.getByRole("button", { name: "Close", exact: true }).click()
    await retry()
    assert.deepEqual((await requests(page)).slice(1).flatMap((request) => request.body.deleteContactIds), deletedIds)
    assert.ok((await requests(page)).every((request) => request.body.deleteContactIds && !request.body.contactIds))
    assert.deepEqual(await retries(page), [])
    console.log("PASS: failed company deletion cannot lose already-deleted contacts; all remote deletes remain retryable")

    await reset()
    await selectCompany()
    await page.evaluate(() => { window.__phonebookSyncHarness.syncPlan.push({ malformed: true }) })
    await syncCompany()
    await page.getByText(/incomplete verification response/).waitFor()
    assert.deepEqual((await retries(page)).map((entry) => entry.id).sort(), ["synthetic-contact-a", "synthetic-contact-b", "synthetic-contact-c"])
    await retry()
    assert.deepEqual(await retries(page), [])
    console.log("PASS: malformed HTTP 200 is not treated as success; every unverified contact remains retryable")

    await reset()
    await selectCompany()
    await page.evaluate(() => { window.__phonebookSyncHarness.malformedContacts = true })
    await syncCompany()
    await page.getByText(/complete saved contact list could not be verified/).waitFor()
    assert.deepEqual(await requests(page), [])
    console.log("PASS: incomplete company-list response cannot silently report successful sync")

    await reset()
    await selectCompany()
    await page.evaluate((key) => localStorage.setItem(key, "broken-json"), RETRY_KEY)
    await syncCompany()
    await page.getByText(/retry information is unreadable/).waitFor()
    assert.deepEqual(await requests(page), [])
    assert.equal(await page.evaluate((key) => localStorage.getItem(key), RETRY_KEY), "broken-json")
    console.log("PASS: corrupt retry storage fails visibly without erasing evidence or sending untracked sync")

    await reset()
    await button(page, "☰").click()
    let resyncPrompt = ""
    page.once("dialog", async (dialog) => { resyncPrompt = dialog.message(); await dialog.accept() })
    await button(page, "Resync all contacts").click()
    await button(page, "Sync selected company").waitFor()
    await settle(page)
    assert.ok(resyncPrompt)
    const fullRequests = await requests(page)
    assert.equal(fullRequests.length, 2)
    assert.ok(fullRequests.every((request) => request.body.fullRebuild === true && request.body.phase === "upload" && !request.body.deleteContactIds))
    assert.deepEqual(fullRequests.map((request) => request.body.cursor), [0, 2])
    assert.deepEqual(await retries(page), [])
    console.log("PASS: full resync uses increasing upload-only batches and never deletes first")

    assert.deepEqual(errors, [], "no browser errors")
    assert.deepEqual(blockedRequests, [], "no external browser requests")
    console.log("PASS: Phonebook browser regressions completed using isolated synthetic data only")
  } finally {
    if (browser) await browser.close()
    await new Promise((resolve) => server.close(resolve))
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1 })
