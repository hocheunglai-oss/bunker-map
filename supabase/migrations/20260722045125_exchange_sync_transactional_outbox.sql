update public.shared_addressbook_groups as groups
set member_count = counts.member_count
from (
  select groups_inner.id, count(members.contact_id)::integer as member_count
  from public.shared_addressbook_groups as groups_inner
  left join public.shared_addressbook_group_members as members
    on members.group_id = groups_inner.id
  group by groups_inner.id
) as counts
where groups.id = counts.id
  and groups.member_count is distinct from counts.member_count;

