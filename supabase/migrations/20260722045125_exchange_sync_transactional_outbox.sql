create or replace function public.audit_table_changes()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  before_payload jsonb;
  after_payload jsonb;
  changed text[];
  actor_id text;
  actor_name text;
  actor_source text;
  context_payload jsonb;
  undo_of uuid;
  correlation_id uuid;
begin
  if tg_table_schema = 'public' and tg_table_name = 'audit_logs' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  before_payload := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  after_payload := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;

  if tg_op = 'UPDATE' then
    changed := array_remove(public.audit_changed_fields(before_payload, after_payload), 'updated_at');
    if coalesce(array_length(changed, 1), 0) = 0 then return new; end if;
    if tg_table_name = 'shared_addressbook_groups'
      and changed <@ array['member_count']::text[]
    then
      return new;
    end if;
  else
    changed := array[]::text[];
  end if;

  if tg_table_name = 'office_calendar_store'
    and coalesce(coalesce(after_payload, before_payload) ->> 'key', '')
      not in ('event-calendar', 'task-calendar')
  then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  actor_id := coalesce(
    nullif(public.audit_text_setting('app.audit_actor_id'), ''),
    nullif(public.audit_request_header('x-bunker-admin-user'), '')
  );

  if actor_id is null then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  actor_name := coalesce(
    nullif(public.audit_text_setting('app.audit_actor_name'), ''),
    nullif(public.audit_request_header('x-bunker-admin-display-name'), ''),
    actor_id
  );
  actor_source := case
    when nullif(public.audit_text_setting('app.audit_actor_id'), '') is not null then 'app'
    else 'header'
  end;

  correlation_id := public.audit_uuid_setting('app.audit_correlation_id');
  if correlation_id is null then
    correlation_id := gen_random_uuid();
    perform set_config('app.audit_correlation_id', correlation_id::text, true);
  end if;

  context_payload := coalesce(
    public.audit_json_setting('app.audit_context'),
    '{}'::jsonb
  ) || jsonb_strip_nulls(jsonb_build_object(
    'pageId', nullif(public.audit_request_header('x-bunker-admin-page-id'), ''),
    'pageLabel', nullif(public.audit_request_header('x-bunker-admin-page-label'), ''),
    'pagePath', nullif(public.audit_request_header('x-bunker-admin-page-path'), ''),
    'correlationId', correlation_id
  ));
  undo_of := public.audit_uuid_setting('app.audit_undo_of_log_id');

  insert into public.audit_logs (
    actor_id,
    actor_name,
    actor_source,
    table_schema,
    table_name,
    operation,
    record_pk,
    changed_fields,
    before_row,
    after_row,
    request_context,
    undo_of_log_id
  ) values (
    actor_id,
    actor_name,
    actor_source,
    tg_table_schema,
    tg_table_name,
    tg_op,
    public.audit_row_pk(tg_table_schema, tg_table_name, coalesce(after_payload, before_payload)),
    changed,
    before_payload,
    after_payload,
    context_payload,
    undo_of
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

create or replace function public.outlook_exchange_alias(
  p_value text,
  p_fallback text
)
returns text
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    nullif(
      left(
        regexp_replace(
          regexp_replace(
            lower(regexp_replace(coalesce(nullif(btrim(p_value), ''), p_fallback), '&', ' and ', 'g')),
            '[^a-z0-9._-]+',
            '-',
            'g'
          ),
          '^[.-]+|[.-]+$',
          '',
          'g'
        ),
        58
      ),
      ''
    ),
    p_fallback
  );
$$;

create or replace function public.outlook_exchange_queue_source_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  before_payload jsonb;
  after_payload jsonb;
  earliest_before jsonb;
  changed text[];
  audit_actor_id_value text;
  actor_id_value text;
  actor_name_value text;
  action_value text;
  entity_type_value text;
  entity_id_value text;
  entity_key_value text;
  entity_email_value text;
  entity_alias_value text;
  display_name_value text;
  source_version_value timestamptz;
  payload_value jsonb;
  before_key text;
  after_key text;
  audit_log_id_value uuid;
  audit_log_ids_value uuid[];
  change_set_id_value uuid;
  change_set_ids_value uuid[];
  group_row public.shared_addressbook_groups%rowtype;
  contact_row public.shared_addressbook_contacts%rowtype;
  pending_queue public.outlook_exchange_sync_queue%rowtype;
  operation_history jsonb;
begin
  before_payload := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  after_payload := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
  changed := case
    when tg_op = 'UPDATE' then array_remove(public.audit_changed_fields(before_payload, after_payload), 'updated_at')
    else array[]::text[]
  end;

  if tg_op = 'UPDATE' and coalesce(array_length(changed, 1), 0) = 0 then
    return new;
  end if;
  if tg_table_name = 'shared_addressbook_groups'
    and tg_op = 'UPDATE'
    and changed <@ array['member_count']::text[]
  then
    return new;
  end if;

  audit_actor_id_value := coalesce(
    nullif(public.audit_text_setting('app.audit_actor_id'), ''),
    nullif(public.audit_request_header('x-bunker-admin-user'), '')
  );
  if audit_actor_id_value is null or lower(audit_actor_id_value) = 'unknown' then
    raise exception 'Address book changes require an authenticated audit actor.';
  end if;
  actor_id_value := audit_actor_id_value;
  actor_name_value := coalesce(
    nullif(public.audit_text_setting('app.audit_actor_name'), ''),
    nullif(public.audit_request_header('x-bunker-admin-display-name'), ''),
    actor_id_value
  );
  change_set_id_value := public.audit_uuid_setting('app.audit_correlation_id');

  if tg_table_name = 'shared_addressbook_contacts' then
    before_key := 'beforeContact';
    after_key := 'afterContact';
    action_value := case tg_op
      when 'INSERT' then 'create_contact'
      when 'DELETE' then 'delete_contact'
      else 'update_contact'
    end;
    entity_type_value := 'contact';
    entity_id_value := coalesce(after_payload->>'id', before_payload->>'id');
    entity_key_value := 'contact:' || entity_id_value;
    entity_email_value := lower(nullif(btrim(coalesce(after_payload->>'primary_email', before_payload->>'primary_email')), ''));
    display_name_value := nullif(btrim(coalesce(after_payload->>'display_name', before_payload->>'display_name')), '');
    entity_alias_value := public.outlook_exchange_alias(
      coalesce(
        nullif(after_payload->>'nickname', ''),
        nullif(after_payload->>'display_name', ''),
        nullif(before_payload->>'nickname', ''),
        nullif(before_payload->>'display_name', '')
      ),
      'contact-' || entity_id_value
    );
  elsif tg_table_name = 'shared_addressbook_groups' then
    before_key := 'beforeGroup';
    after_key := 'afterGroup';
    action_value := case tg_op
      when 'INSERT' then 'create_group'
      when 'DELETE' then 'delete_group'
      else 'update_group'
    end;
    entity_type_value := 'group';
    entity_id_value := coalesce(after_payload->>'id', before_payload->>'id');
    entity_key_value := 'group:' || entity_id_value;
    display_name_value := nullif(btrim(coalesce(after_payload->>'name', before_payload->>'name')), '');
    entity_alias_value := public.outlook_exchange_alias(
      coalesce(
        nullif(after_payload->>'nickname', ''),
        nullif(after_payload->>'name', ''),
        nullif(before_payload->>'nickname', ''),
        nullif(before_payload->>'name', '')
      ),
      'group-' || entity_id_value
    );
  elsif tg_table_name = 'shared_addressbook_group_members' then
    before_key := 'beforeMember';
    after_key := 'afterMember';
    action_value := 'update_group_members';
    entity_type_value := 'group_members';
    entity_id_value := coalesce(after_payload->>'group_id', before_payload->>'group_id');
    entity_key_value := concat_ws(
      ':',
      'group_members',
      entity_id_value,
      coalesce(after_payload->>'contact_id', before_payload->>'contact_id')
    );
    select * into group_row
    from public.shared_addressbook_groups
    where id = entity_id_value;
    select * into contact_row
    from public.shared_addressbook_contacts
    where id = coalesce(after_payload->>'contact_id', before_payload->>'contact_id');
    display_name_value := nullif(btrim(group_row.name), '');
    entity_alias_value := public.outlook_exchange_alias(
      coalesce(nullif(group_row.nickname, ''), nullif(group_row.name, '')),
      'group-' || entity_id_value
    );
  else
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  source_version_value := coalesce(
    nullif(after_payload->>'updated_at', '')::timestamptz,
    nullif(before_payload->>'updated_at', '')::timestamptz,
    clock_timestamp()
  );

  if change_set_id_value is not null then
    select logs.id into audit_log_id_value
    from public.audit_logs as logs
    where logs.table_schema = tg_table_schema
      and logs.table_name = tg_table_name
      and logs.operation = tg_op
      and logs.actor_id = audit_actor_id_value
      and logs.request_context->>'correlationId' = change_set_id_value::text
      and logs.record_pk = public.audit_row_pk(
        tg_table_schema,
        tg_table_name,
        coalesce(after_payload, before_payload)
      )
      and logs.before_row is not distinct from before_payload
      and logs.after_row is not distinct from after_payload
    order by logs.occurred_at desc, logs.id desc
    limit 1;
  end if;

  audit_log_ids_value := case
    when audit_log_id_value is null then array[]::uuid[]
    else array[audit_log_id_value]
  end;
  change_set_ids_value := case
    when change_set_id_value is null then array[]::uuid[]
    else array[change_set_id_value]
  end;
  operation_history := jsonb_build_array(tg_op);

  payload_value := jsonb_build_object(
    before_key, before_payload,
    after_key, after_payload,
    'group', case when group_row.id is null then null else to_jsonb(group_row) end,
    'contact', case when contact_row.id is null then null else to_jsonb(contact_row) end,
    'changedFields', to_jsonb(changed),
    'operationHistory', operation_history,
    'auditLogIds', to_jsonb(audit_log_ids_value),
    'changeSetIds', to_jsonb(change_set_ids_value),
    'userAuthorized', true
  );

  select queue.* into pending_queue
  from public.outlook_exchange_sync_queue as queue
  where queue.status = 'pending'
    and queue.entity_key = entity_key_value
    and queue.actor_id = actor_id_value
  order by queue.queue_sequence desc
  limit 1
  for update;

  if pending_queue.id is not null then
    earliest_before := case
      when pending_queue.payload ? before_key then pending_queue.payload -> before_key
      else before_payload
    end;
    changed := array_remove(
      public.audit_changed_fields(nullif(earliest_before, 'null'::jsonb), after_payload),
      'updated_at'
    );
    audit_log_ids_value := coalesce(pending_queue.audit_log_ids, array[]::uuid[]);
    if audit_log_id_value is not null and not audit_log_id_value = any(audit_log_ids_value) then
      audit_log_ids_value := array_append(audit_log_ids_value, audit_log_id_value);
    end if;
    change_set_ids_value := coalesce(pending_queue.change_set_ids, array[]::uuid[]);
    if change_set_id_value is not null and not change_set_id_value = any(change_set_ids_value) then
      change_set_ids_value := array_append(change_set_ids_value, change_set_id_value);
    end if;
    operation_history := coalesce(pending_queue.payload->'operationHistory', '[]'::jsonb) || jsonb_build_array(tg_op);

    if entity_type_value = 'contact' then
      action_value := case
        when (earliest_before is null or earliest_before = 'null'::jsonb) and after_payload is not null then 'create_contact'
        when after_payload is null then 'delete_contact'
        else 'update_contact'
      end;
    elsif entity_type_value = 'group' then
      action_value := case
        when (earliest_before is null or earliest_before = 'null'::jsonb) and after_payload is not null then 'create_group'
        when after_payload is null then 'delete_group'
        else 'update_group'
      end;
    end if;

    payload_value := payload_value || jsonb_build_object(
      before_key, earliest_before,
      after_key, after_payload,
      'changedFields', to_jsonb(changed),
      'operationHistory', operation_history,
      'auditLogIds', to_jsonb(audit_log_ids_value),
      'changeSetIds', to_jsonb(change_set_ids_value)
    );

    update public.outlook_exchange_sync_queue
    set action = action_value,
        entity_id = entity_id_value,
        entity_email = entity_email_value,
        entity_alias = entity_alias_value,
        display_name = display_name_value,
        payload = payload_value,
        requested_by = actor_name_value,
        audit_log_id = audit_log_id_value,
        audit_log_ids = audit_log_ids_value,
        change_set_id = change_set_id_value,
        change_set_ids = change_set_ids_value,
        changed_fields = changed,
        source_version = source_version_value,
        updated_at = clock_timestamp()
    where id = pending_queue.id
      and status = 'pending';
  else
    insert into public.outlook_exchange_sync_queue (
      action,
      entity_type,
      entity_id,
      entity_key,
      entity_email,
      entity_alias,
      display_name,
      payload,
      requested_by,
      actor_id,
      audit_log_id,
      audit_log_ids,
      change_set_id,
      change_set_ids,
      changed_fields,
      source_version
    ) values (
      action_value,
      entity_type_value,
      entity_id_value,
      entity_key_value,
      entity_email_value,
      entity_alias_value,
      display_name_value,
      payload_value,
      actor_name_value,
      actor_id_value,
      audit_log_id_value,
      audit_log_ids_value,
      change_set_id_value,
      change_set_ids_value,
      changed,
      source_version_value
    );
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

