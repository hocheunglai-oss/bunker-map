create or replace function public.acquire_outlook_exchange_sync_lock(
  p_run_id uuid,
  p_sync_mode text,
  p_lease_minutes integer default 30
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  acquired boolean := false;
begin
  if p_run_id is null then raise exception 'p_run_id is required'; end if;
  insert into public.outlook_exchange_sync_lock (
    lock_name, run_id, sync_mode, acquired_at, heartbeat_at, expires_at
  ) values (
    'addressbook', p_run_id, coalesce(nullif(p_sync_mode, ''), 'incremental'),
    clock_timestamp(), clock_timestamp(),
    clock_timestamp() + make_interval(mins => greatest(5, least(coalesce(p_lease_minutes, 30), 180)))
  )
  on conflict (lock_name) do update
  set run_id = excluded.run_id,
      sync_mode = excluded.sync_mode,
      acquired_at = excluded.acquired_at,
      heartbeat_at = excluded.heartbeat_at,
      expires_at = excluded.expires_at
  where public.outlook_exchange_sync_lock.expires_at <= clock_timestamp()
     or public.outlook_exchange_sync_lock.run_id = excluded.run_id
  returning true into acquired;
  return coalesce(acquired, false);
end;
$$;

create or replace function public.renew_outlook_exchange_sync_lock(
  p_run_id uuid,
  p_lease_minutes integer default 30
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  renewed boolean := false;
begin
  update public.outlook_exchange_sync_lock
  set heartbeat_at = clock_timestamp(),
      expires_at = clock_timestamp() + make_interval(mins => greatest(5, least(coalesce(p_lease_minutes, 30), 180)))
  where lock_name = 'addressbook'
    and run_id = p_run_id
    and expires_at > clock_timestamp()
  returning true into renewed;
  return coalesce(renewed, false);
end;
$$;

create or replace function public.release_outlook_exchange_sync_lock(p_run_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  released boolean := false;
begin
  delete from public.outlook_exchange_sync_lock
  where lock_name = 'addressbook' and run_id = p_run_id
  returning true into released;
  return coalesce(released, false);
end;
$$;

